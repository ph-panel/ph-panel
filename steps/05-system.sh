#!/usr/bin/env bash
# Step 05 – system configuration: local DNS resolver [05], journald [43], security updates [19],
# per-user quotas [29], nftables firewall [09]. It only writes configuration; starting happens in step 08.

setup_resolver() {
  # systemd-resolved without a stub on :53 (Unbound occupies 127.0.0.1:53), Unbound local only, with root hints, no forwarding
  write_file /etc/systemd/resolved.conf.d/phpanel.conf <<'CONF'
[Resolve]
DNSStubListener=no
CONF
  local hints=/usr/share/dns/root.hints
  [[ -f $hints ]] || warn "$hints is missing (dns-root-data package); Unbound uses its compiled-in hints"
  write_file /etc/unbound/unbound.conf.d/phpanel.conf <<CONF
# Generated by PH-PANEL. Listens locally only; Knot is the only service on the public IP:53 [05].
server:
    interface: 127.0.0.1
    port: 53
    access-control: 0.0.0.0/0 refuse
    access-control: 127.0.0.0/8 allow
$( [[ -f $hints ]] && echo "    root-hints: \"$hints\"" )
    hide-identity: yes
    hide-version: yes
    qname-minimisation: yes
    prefetch: yes
    num-threads: $(pick 1 1 2 "$CPUS")
    msg-cache-size: $(pick 4m 8m 16m 32m)
    rrset-cache-size: $(pick 8m 16m 32m 64m)
CONF
  write_file /etc/systemd/system/unbound.service.d/phpanel.conf <<'CONF'
[Service]
Restart=always
RestartSec=2
CONF
  # DNSSEC trust anchor for the first start: unbound-anchor (separate package on 26.04), otherwise the copy from dns-root-data
  if [[ $DRY_RUN != 1 && ! -s /var/lib/unbound/root.key ]]; then
    if have unbound-anchor; then unbound-anchor -a /var/lib/unbound/root.key >>"$PHPANEL_LOG_FILE" 2>&1 || true; fi
    if [[ ! -s /var/lib/unbound/root.key && -f /usr/share/dns/root.key ]]; then cp /usr/share/dns/root.key /var/lib/unbound/root.key; fi
    chown unbound:unbound /var/lib/unbound/root.key 2>/dev/null || true
    [[ -s /var/lib/unbound/root.key ]] || warn "Unbound: /var/lib/unbound/root.key is missing (DNSSEC); it will not start"
  fi
  # unbound-resolvconf would rewrite /etc/resolv.conf
  if systemctl list-unit-files unbound-resolvconf.service --no-legend 2>/dev/null | grep -q .; then
    run systemctl disable unbound-resolvconf.service || true
  fi
}

setup_journald() {
  write_file /etc/systemd/journald.conf.d/phpanel.conf <<'CONF'
[Journal]
SystemMaxUse=100M
CONF
}

# I/O accounting for services [70]: the history graphs show disk reads and writes per service. CPU, memory and tasks are on by default.
setup_accounting() {
  write_file /etc/systemd/system.conf.d/phpanel-accounting.conf <<'CONF'
[Manager]
DefaultIOAccounting=yes
CONF
}

setup_unattended() {
  # Security updates only, every night at 03:00 [19]. The full upgrade stays manual (Admin -> Updates), and nothing restarts the server by
  # itself: a restart is the administrator's choice. The origins are written out here instead of trusting the distribution's defaults, and the
  # distribution's own lists are cleared first, so "-updates" can never come back through a later change of those defaults.
  local id; id=$(. /etc/os-release 2>/dev/null; echo "${ID:-}")
  write_file /etc/apt/apt.conf.d/20auto-upgrades <<'CONF'
APT::Periodic::Update-Package-Lists "1";
APT::Periodic::Unattended-Upgrade "1";
CONF
  case $id in
    ubuntu)
      write_file /etc/apt/apt.conf.d/52phpanel-upgrades <<'CONF'
// PH-PANEL [19]: security updates only, no automatic restart.
#clear Unattended-Upgrade::Allowed-Origins;
#clear Unattended-Upgrade::Origins-Pattern;
Unattended-Upgrade::Allowed-Origins {
        "${distro_id}:${distro_codename}-security";
        "${distro_id}ESMApps:${distro_codename}-apps-security";
        "${distro_id}ESM:${distro_codename}-infra-security";
};
Unattended-Upgrade::Automatic-Reboot "false";
Unattended-Upgrade::Remove-Unused-Dependencies "false";
CONF
      ;;
    debian)
      write_file /etc/apt/apt.conf.d/52phpanel-upgrades <<'CONF'
// PH-PANEL [19]: security updates only, no automatic restart.
#clear Unattended-Upgrade::Allowed-Origins;
#clear Unattended-Upgrade::Origins-Pattern;
Unattended-Upgrade::Origins-Pattern {
        "origin=Debian,codename=${distro_codename}-security,label=Debian-Security";
        "origin=Debian,codename=${distro_codename},label=Debian-Security";
};
Unattended-Upgrade::Automatic-Reboot "false";
Unattended-Upgrade::Remove-Unused-Dependencies "false";
CONF
      ;;
    *)
      write_file /etc/apt/apt.conf.d/52phpanel-upgrades <<'CONF'
// PH-PANEL [19]: no automatic restart.
Unattended-Upgrade::Automatic-Reboot "false";
Unattended-Upgrade::Remove-Unused-Dependencies "false";
CONF
      ;;
  esac
  write_file /etc/systemd/system/apt-daily-upgrade.timer.d/phpanel.conf <<'CONF'
[Timer]
OnCalendar=
OnCalendar=*-*-* 03:00
RandomizedDelaySec=0
CONF
  run systemctl daemon-reload || true
  run systemctl enable --now apt-daily.timer apt-daily-upgrade.timer || warn "the timers of the automatic security updates could not be enabled"
}

setup_quota() {
  # [29] per-user Linux quotas, without reboot, on the root partition (ext4). Any failure = warning, no changes to fstab.
  local fstype; fstype=$(findmnt -no FSTYPE / 2>/dev/null || true)
  if [[ $fstype != ext4 ]]; then
    warn "quota: / is '$fstype'; per-user quotas require ext4 (on xfs they are enabled at mount time) [29]"
    return 0
  fi
  [[ $DRY_RUN == 1 ]] && { info "[dry-run] enabling quotas on /"; return 0; }
  local qs; qs=$(quotaon -up / 2>&1 || true)
  if grep -q 'user quota on.*is on' <<<"$qs"; then ok "per-user quotas already active"; return 0; fi
  if ! modprobe quota_v2 2>/dev/null; then
    apt_install_group "quota" "linux-modules-extra-$(uname -r)"
    modprobe quota_v2 2>/dev/null || { warn "quota: the quota_v2 kernel module is missing; quotas remain disabled [29]"; return 0; }
  fi
  if run mount -o remount,usrjquota=aquota.user,jqfmt=vfsv1 / \
     && run quotacheck -cum / \
     && run quotaon -u /; then
    if ! grep -qE '^[^#]\S*\s+/\s+ext4\s+\S*usrjquota' /etc/fstab; then
      cp /etc/fstab "$PHPANEL_STATE_DIR/fstab.bak"
      awk '$1!~/^#/ && $2=="/" && $3=="ext4" && $4!~/usrjquota/ {$4=$4",usrjquota=aquota.user,jqfmt=vfsv1"} {print}' \
        "$PHPANEL_STATE_DIR/fstab.bak" >/etc/fstab
    fi
    ok "per-user quotas active on / (no reboot)"
  else
    warn "quota: remount/quotacheck/quotaon failed; quotas remain disabled [29]"
    run mount -o remount / || true
  fi
}

setup_firewall() {
  # nftables default deny [09]. Only the 'inet phpanel' table is managed by us (we do not flush the ruleset).
  # The real SSH port is detected, so we do not lock ourselves out.
  local ssh_ports; ssh_ports=$(ss -ltnpH 2>/dev/null | awk '/"sshd"/ {n=split($4,a,":"); print a[n]}' | sort -un | paste -sd, -)
  ssh_ports=${ssh_ports:-22}
  local ports='21, 25, 53, 80, 443, 465, 587, 990, 993, 995, 8443' passive='tcp dport 30000-31000 accept'
  if dns_only; then ports='53, 80, 443, 8443'; passive=''; fi   # a name server: DNS, the ACME answer and the panel
  write_file /etc/nftables.conf 644 <<CONF
#!/usr/sbin/nft -f
# Generated by PH-PANEL – do not edit manually [09]
table inet phpanel
delete table inet phpanel
table inet phpanel {
    # bans received from the cluster [50]; elements expire on their own
    set phpanel_cluster_ban4 { type ipv4_addr; flags timeout; }
    set phpanel_cluster_ban6 { type ipv6_addr; flags timeout; }

    chain input {
        type filter hook input priority filter; policy drop;
        iif lo accept
        ct state established,related accept
        ct state invalid drop
        ip saddr @phpanel_cluster_ban4 drop
        ip6 saddr @phpanel_cluster_ban6 drop
        ip protocol icmp accept
        meta l4proto ipv6-icmp accept
        tcp dport { $ssh_ports, $ports } accept
        udp dport { 53, 443 } accept
        $passive
    }
}
include "/etc/phpanel/loopback-guard.nft"
CONF
  if [[ $DRY_RUN != 1 ]]; then
    install -d /etc/phpanel
    [[ -f /etc/phpanel/loopback-guard.nft ]] || printf 'table inet phpanel_lo\n' >/etc/phpanel/loopback-guard.nft
    if nft -c -f /etc/nftables.conf >>"$PHPANEL_LOG_FILE" 2>&1; then
      ok "nftables rules valid (SSH: $ssh_ports)"
    else
      error "nft -c rejected /etc/nftables.conf; the firewall will NOT be enabled"
      mv /etc/nftables.conf /etc/nftables.conf.rejected
    fi
  fi
  # iptables preinstalled by the provider (e.g. Oracle) [46]
  if systemctl list-unit-files netfilter-persistent.service --no-legend 2>/dev/null | grep -q .; then
    run systemctl disable --now netfilter-persistent.service || true
    run iptables -F || true
    info "netfilter-persistent disabled (switching to nftables)"
  fi
}

# The services on 127.0.0.1 that are not for hosting accounts (the Apache backend behind Caddy and its status page, the autoconfig answer of the
# panel, Rspamd's workers) are closed to every local user except the accounts that use them. Hosting accounts (PHP, cron, SSH) can open any
# loopback port, so this is checked per connecting user in the output path. Only users that exist are listed; unknown ones are skipped.
setup_loopback_guard() {
  dns_only && return 0
  local u ids
  uids() { local out="" x; for x in "$@"; do id -u "$x" >/dev/null 2>&1 && out+="${out:+, }$(id -u "$x")"; done; printf '%s' "$out"; }
  local web stat rsp wmu
  web=$(uids root caddy phpanel); stat=$(uids root phpanel); rsp=$(uids root postfix _rspamd); wmu=$(uids root webmail)
  [[ -n $wmu ]] || wmu=0
  write_file /etc/phpanel/loopback-guard.nft 644 <<CONF
#!/usr/sbin/nft -f
# Generated by PH-PANEL – local services closed to hosting accounts (only the listed users may connect)
table inet phpanel_lo
delete table inet phpanel_lo
table inet phpanel_lo {
    chain output {
        type filter hook output priority filter; policy accept;
        oif != "lo" return
        # Apache backend (behind Caddy and its web firewall), the Apache status page and the panel's autoconfig answer
        ip daddr 127.0.0.0/8 tcp dport { 8080, 8479 } meta skuid != { $web } reject with tcp reset
        ip6 daddr ::1 tcp dport { 8080, 8479 } meta skuid != { $web } reject with tcp reset
        ip daddr 127.0.0.0/8 tcp dport 8079 meta skuid != { $stat } reject with tcp reset
        ip6 daddr ::1 tcp dport 8079 meta skuid != { $stat } reject with tcp reset
        # Rspamd's mail workers (Postfix asks them; nobody else needs to)
        ip daddr 127.0.0.0/8 tcp dport { 11332, 11333, 11334 } meta skuid != { $rsp } reject with tcp reset
        ip6 daddr ::1 tcp dport { 11332, 11333, 11334 } meta skuid != { $rsp } reject with tcp reset
        # the port that hands system mail to the SMTP account (only the panel and the cron runner may use it; an account of a hosting customer cannot)
        ip daddr 127.0.0.0/8 tcp dport 2526 meta skuid != { $stat } reject with tcp reset
        ip6 daddr ::1 tcp dport 2526 meta skuid != { $stat } reject with tcp reset
        # the address book of webmail (contacts) is served here to the webmail program only
        ip daddr 127.0.0.0/8 tcp dport 8095 meta skuid != { $wmu } reject with tcp reset
        ip6 daddr ::1 tcp dport 8095 meta skuid != { $wmu } reject with tcp reset
    }
}
CONF
  if [[ $DRY_RUN != 1 ]]; then
    if nft -c -f /etc/phpanel/loopback-guard.nft >>"$PHPANEL_LOG_FILE" 2>&1; then
      # on the running firewall at once (a server that is being updated does not wait for a restart of the nftables service)
      if nft -f /etc/phpanel/loopback-guard.nft >>"$PHPANEL_LOG_FILE" 2>&1; then ok "local services are closed to hosting accounts (nftables)"; else warn "the loopback guard could not be loaded (see $PHPANEL_LOG_FILE)"; fi
    else
      error "nft -c rejected the loopback guard; hosting accounts can still reach the local services"
    fi
  fi
}

step_05_system() {
  setup_resolver
  setup_journald
  setup_accounting
  setup_unattended
  dns_only || setup_quota
  setup_firewall
  setup_loopback_guard
}
