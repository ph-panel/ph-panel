#!/usr/bin/env bash
# Step 07 – data and access: MariaDB [44][38], Redis [43], Knot [04], Pure-FTPd [17], Fail2Ban [09].
# Configuration only; starting happens in step 08.

setup_mariadb() {
  [[ -d /etc/mysql ]] || { info "mariadb not installed, skipping"; return 0; }
  local prof=/opt/phpanel/mysql-profiles
  install -d -m 755 /opt/phpanel /opt/phpanel/mysql-profiles /var/log/mysql
  chown mysql:adm /var/log/mysql 2>/dev/null || true
  local names=(p01 p02 p03 p04 p05 p06 p07 p08 p09 p10)
  local bp=(128M 256M 512M 768M 1G 2G 3G 4G 8G 16G)
  local mc=(30 50 75 100 150 200 300 400 500 800)
  local tmp=(16M 32M 32M 64M 64M 64M 128M 128M 256M 256M)
  local redo=(48M 64M 128M 128M 256M 256M 512M 512M 1G 2G)
  local ps=(OFF OFF OFF OFF OFF ON ON ON ON ON)
  local i
  for i in "${!names[@]}"; do
    write_file "$prof/${names[$i]}.cnf" <<CONF
# MariaDB profile ${names[$i]} [44] – generated by PH-PANEL
[mysqld]
bind-address = 127.0.0.1
innodb_buffer_pool_size = ${bp[$i]}
max_connections = ${mc[$i]}
tmp_table_size = ${tmp[$i]}
max_heap_table_size = ${tmp[$i]}
innodb_log_file_size = ${redo[$i]}
performance_schema = ${ps[$i]}
slow_query_log = ON
slow_query_log_file = /var/log/mysql/slow.log
long_query_time = 2
CONF
  done
  # hardware-based adjustments
  local rot io=1000 flush=0 f=/sys/block
  rot=$(cat $f/sd*/queue/rotational $f/vd*/queue/rotational $f/nvme*/queue/rotational 2>/dev/null | head -1 || true)
  [[ ${rot:-0} == 1 ]] && { io=200; flush=1; }
  write_file /etc/mysql/mariadb.conf.d/91-phpanel-hw.cnf <<CONF
[mysqld]
thread_handling = pool-of-threads
thread_pool_size = ${CPUS:-1}
innodb_io_capacity = $io
innodb_flush_neighbors = $flush
CONF
  # hardening beyond the distribution defaults: no LOAD DATA LOCAL. skip_name_resolve is deliberately NOT set: with it,
  # 'user'@'localhost' accounts stop working over TCP (127.0.0.1), which breaks software that connects that way.
  write_file /etc/mysql/mariadb.conf.d/92-phpanel-security.cnf <<'CONF'
[mysqld]
local_infile = 0
CONF
  # a copy, not a symlink: AppArmor (mariadbd) does not allow reading from /opt
  if [[ $DRY_RUN != 1 ]]; then
    cp -f "$prof/${MYCNF_PROFILE:-p02}.cnf" /etc/mysql/mariadb.conf.d/90-phpanel.cnf
  fi
  ok "MariaDB profile ${MYCNF_PROFILE:-p02} ready"
}

setup_redis() {
  [[ -f /etc/redis/redis.conf ]] || return 0
  write_file /etc/redis/phpanel.conf 640 <<CONF
# Generated by PH-PANEL [43]: Redis for Rspamd
bind 127.0.0.1
maxmemory $(pick 32mb 64mb 128mb 256mb)
maxmemory-policy allkeys-lru
CONF
  chown redis:redis /etc/redis/phpanel.conf 2>/dev/null || true
  if [[ $DRY_RUN != 1 ]] && ! grep -q '^include /etc/redis/phpanel.conf' /etc/redis/redis.conf; then
    echo 'include /etc/redis/phpanel.conf' >>/etc/redis/redis.conf
  fi
}

setup_knot() {
  have knotc || { info "knot not installed, skipping"; return 0; }
  fact_set KNOT_OK 0
  if [[ -z ${IP_LOCAL:-} ]]; then warn "Knot: no local IP to listen on; it stays stopped"; return 0; fi
  [[ $DRY_RUN == 1 ]] && { info "[dry-run] configuring Knot"; return 0; }
  install -d -m 750 -o knot -g knot /var/lib/knot/zones
  if [[ ! -s /etc/knot/tsig.key ]]; then
    ( umask 077; printf 'key:\n  - id: phpanel-tsig\n    algorithm: hmac-sha256\n    secret: %s\n' "$(openssl rand -base64 32)" >/etc/knot/tsig.key )
  fi
  chown root:knot /etc/knot/tsig.key; chmod 640 /etc/knot/tsig.key
  local node; node=$(hostname -s | tr -c 'a-z0-9\n' '-')
  # zones of hosted domains; created once and then maintained by the panel, never overwritten here
  [[ -f /etc/knot/phpanel-zones.conf ]] || printf '# PH-PANEL zones; maintained by the panel\n' >/etc/knot/phpanel-zones.conf
  write_file /etc/knot/knot.conf <<CONF
# Generated by PH-PANEL [04][48]. Listens on the server IP (the internal one, in NAT mode).
server:
    rundir: "/run/knot"
    user: knot:knot
    listen: ${IP_LOCAL}@53

include: "/etc/knot/tsig.key"

log:
  - target: syslog
    any: info

database:
    storage: "/var/lib/knot"

template:
  - id: default
    storage: "/var/lib/knot/zones"
    file: "%s.zone"
  - id: phpanel-catalog
    storage: "/var/lib/knot/zones"
    file: "%s.zone"
    catalog-role: generate

zone:
  - domain: catalog.${node}.phpanel.invalid
    template: phpanel-catalog

# hosted zones; included last because they reference the templates above
include: "/etc/knot/phpanel-zones.conf"
CONF
  if knotc conf-check >>"$PHPANEL_LOG_FILE" 2>&1; then
    ok "knot.conf valid (catalog.${node}.phpanel.invalid)"; fact_set KNOT_OK 1
  else
    error "knotc conf-check failed; Knot stays stopped (see $PHPANEL_LOG_FILE)"
  fi
}

setup_ftp() {
  [[ -d /etc/pure-ftpd ]] || { info "pure-ftpd not installed, skipping"; return 0; }
  [[ $DRY_RUN == 1 ]] && { info "[dry-run] configuring Pure-FTPd"; return 0; }
  local c=/etc/pure-ftpd/conf
  install -d "$c"
  printf '%s\n' "30000 31000" >"$c/PassivePortRange"
  printf '%s\n' yes >"$c/ChrootEveryone"; printf '%s\n' yes >"$c/NoAnonymous"; printf '%s\n' yes >"$c/DontResolve"
  printf '%s\n' 2 >"$c/TLS"            # TLS mandatory [17]
  printf '%s\n' 1000 >"$c/MinUID"
  printf '%s\n' 8 >"$c/MaxClientsPerIP"
  if [[ ${NAT_MODE:-0} == 1 && -n ${IP_PUBLIC:-} ]]; then printf '%s\n' "$IP_PUBLIC" >"$c/ForcePassiveIP"; else rm -f "$c/ForcePassiveIP"; fi
  # temporary hostname certificate; cert-sync replaces it later [14]
  local pem=/etc/ssl/private/pure-ftpd.pem
  if [[ ! -s $pem ]]; then
    openssl req -x509 -nodes -newkey rsa:2048 -days 397 -subj "/CN=${PANEL_HOSTNAME:-$(hostname -f 2>/dev/null || hostname)}" \
      -keyout "$pem" -out "$pem" >>"$PHPANEL_LOG_FILE" 2>&1 && chmod 600 "$pem" || warn "could not generate the Pure-FTPd certificate"
  fi
  info "explicit FTPS on 21; implicit FTPS on 990 requires a second instance (not handled yet)"
}

setup_fail2ban() {
  [[ -d /etc/fail2ban ]] || return 0
  write_file /etc/fail2ban/jail.d/00-phpanel.conf <<'CONF'
[DEFAULT]
backend = systemd
banaction = nftables
banaction_allports = nftables[type=allports]
ignoreip = 127.0.0.1/8 ::1

[sshd]
enabled = true
backend = systemd

[pure-ftpd]
enabled = true
backend = systemd
journalmatch = SYSLOG_IDENTIFIER=pure-ftpd
CONF
}

step_07_data() {
  setup_mariadb
  setup_redis
  setup_knot
  setup_ftp
  setup_fail2ban
}
