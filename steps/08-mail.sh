#!/usr/bin/env bash
# Step 08 – mail: Postfix, Dovecot 2.4, Rspamd, SRS [05][31]-[34]. Configuration only;
# users and virtual domains come from the panel (the files below start out empty).

mail_hostname() { echo "${PANEL_HOSTNAME:-$(hostname -f 2>/dev/null || hostname)}"; }

setup_dovecot() {
  have doveconf || { info "dovecot not installed, skipping"; return 0; }
  [[ $DRY_RUN == 1 ]] && { info "[dry-run] configuring Dovecot"; return 0; }
  # no PAM authentication: users are virtual, in a passwd-file generated from the DB [F2]
  sed -i 's/^!include auth-system.conf.ext/#!include auth-system.conf.ext/' /etc/dovecot/conf.d/10-auth.conf
  [[ -f /etc/dovecot/phpanel-users ]] || : >/etc/dovecot/phpanel-users
  chown root:dovecot /etc/dovecot/phpanel-users; chmod 640 /etc/dovecot/phpanel-users
  # Webmail signs in through a master user (spec [25]): the secret is created once, its hash goes to Dovecot and
  # only the webmail pool user may read the secret itself. A login with it is accepted from this machine only.
  install -d -m 755 /etc/phpanel
  if [[ ! -s /etc/phpanel/webmail-master.secret ]]; then
    (umask 077; openssl rand -base64 36 | tr -d '/+=\n' >/etc/phpanel/webmail-master.secret)
  fi
  id webmail >/dev/null 2>&1 || useradd --system --home-dir /opt/phpanel/webmail --shell /usr/sbin/nologin webmail
  chown webmail:webmail /etc/phpanel/webmail-master.secret; chmod 600 /etc/phpanel/webmail-master.secret
  local msecret mhash; msecret=$(cat /etc/phpanel/webmail-master.secret)
  mhash=$(doveadm pw -s SHA512-CRYPT -p "$msecret")
  (umask 027; printf 'webmail-sso:%s::::::allow_nets=127.0.0.1\n' "$mhash" >/etc/dovecot/webmail-master)
  chown root:dovecot /etc/dovecot/webmail-master; chmod 640 /etc/dovecot/webmail-master
  # spam moves to Junk for every mailbox; compiled here because Dovecot may not write next to the script
  install -d -m 755 /etc/dovecot/sieve/before.d
  write_file /etc/dovecot/sieve/before.d/10-spam.sieve 644 <<'SIEVE'
require ["fileinto", "mailbox"];
# Rspamd adds "X-Spam: Yes" to messages it judges to be spam (see the milter header settings)
if header :contains "X-Spam" "Yes" {
  fileinto :create "Junk";
  stop;
}
SIEVE
  sievec /etc/dovecot/sieve/before.d/10-spam.sieve >>"$PHPANEL_LOG_FILE" 2>&1 || warn "could not compile the spam filter script"
  write_file /etc/dovecot/local.conf <<'CONF'
# Generated by PH-PANEL. Dovecot 2.4 syntax.
mail_driver = maildir
mail_path = %{home}/Maildir
mail_inbox_path = %{home}/Maildir
mailbox_list_layout = maildir++
auth_mechanisms = plain login
auth_cache_size = 8M
auth_cache_ttl = 5 mins
auth_cache_negative_ttl = 1 mins
auth_master_user_separator = *

# mailbox sizes come from the panel, per mailbox (userdb field quota_storage_size)
mail_plugins {
  quota = yes
}
quota_storage_size = 1G
quota "User quota" {
}
quota_status_nouser = DUNNO
quota_status_overquota = 552 5.2.2 Mailbox is full

ssl_server {
  cert_file = /opt/phpanel/ssl/server/fullchain.pem
  key_file = /opt/phpanel/ssl/server/privkey.pem
}

# The master user of webmail: only the webmail pool knows the secret, and only from 127.0.0.1 [25]
passdb webmail_master {
  driver = passwd-file
  passwd_file_path = /etc/dovecot/webmail-master
  master = yes
  result_success = continue
  default_password_scheme = SHA512-CRYPT
}
# no PAM authentication: users are virtual, in a passwd-file generated from the DB [F2]
passdb panel_users {
  driver = passwd-file
  passwd_file_path = /etc/dovecot/phpanel-users
  default_password_scheme = BLF-CRYPT
}
userdb panel_users {
  driver = passwd-file
  passwd_file_path = /etc/dovecot/phpanel-users
  fields {
    home = %{userdb:home}
  }
}

# the full address is the username (virtual domains)
protocol lmtp {
  auth_username_format = %{user | lower}
  mail_plugins {
    sieve = yes
  }
}
protocol imap {
  mail_plugins {
    imap_quota = yes
  }
}

namespace inbox {
  separator = /
  mailbox Drafts {
    auto = subscribe
  }
  mailbox Junk {
    auto = subscribe
  }
  mailbox Trash {
    auto = subscribe
  }
  mailbox Sent {
    auto = subscribe
  }
}

# filters of the user (managed in webmail), the spam rule of the server and the automatic reply of the panel [31] [32]
sieve_script personal {
  driver = file
  path = ~/sieve
  active_path = ~/.dovecot.sieve
}
sieve_script before_spam {
  type = before
  driver = file
  path = /etc/dovecot/sieve/before.d
}
sieve_script before_user {
  type = before
  driver = file
  path = ~/panel-sieve
}

service auth {
  unix_listener /var/spool/postfix/private/auth {
    mode = 0660
    user = postfix
    group = postfix
  }
}
service lmtp {
  unix_listener /var/spool/postfix/private/dovecot-lmtp {
    mode = 0600
    user = postfix
    group = postfix
  }
}
# Postfix asks here before accepting mail for a full mailbox, so the sender gets the refusal at once [33]
service quota-status {
  executable = quota-status -p postfix
  client_limit = 1
  unix_listener /var/spool/postfix/private/quota-status {
    mode = 0660
    user = postfix
    group = postfix
  }
}
service managesieve-login {
  inet_listener sieve {
    port = 4190
  }
  inet_listener sieve_deprecated {
    port = 0
  }
}
CONF
  if doveconf -n >/dev/null 2>>"$PHPANEL_LOG_FILE"; then ok "Dovecot configuration valid"; else error "doveconf found errors (see $PHPANEL_LOG_FILE)"; fi
}

setup_postfix() {
  have postconf || { info "postfix not installed, skipping"; return 0; }
  [[ $DRY_RUN == 1 ]] && { info "[dry-run] configuring Postfix"; return 0; }
  local host; host=$(mail_hostname)
  local f
  for f in virtual_domains vmailbox valiases vsenders phpanel-hold phpanel-relay; do [[ -f /etc/postfix/$f ]] || : >/etc/postfix/$f; postmap "/etc/postfix/$f"; done
  local cert=/opt/phpanel/ssl/server
  postconf -e \
    "myhostname = $host" \
    "mydestination = \$myhostname, localhost" \
    "smtpd_banner = \$myhostname ESMTP" \
    "message_size_limit = 52428800" \
    "smtpd_tls_cert_file = $cert/fullchain.pem" \
    "smtpd_tls_key_file = $cert/privkey.pem" \
    "smtpd_tls_security_level = may" \
    "smtpd_tls_auth_only = yes" \
    "smtpd_tls_protocols = >=TLSv1.2" \
    "smtp_tls_security_level = may" \
    "smtpd_sasl_type = dovecot" \
    "smtpd_sasl_path = private/auth" \
    "smtpd_sasl_auth_enable = yes" \
    "smtpd_relay_restrictions = permit_mynetworks, permit_sasl_authenticated, reject_unauth_destination" \
    "virtual_mailbox_domains = hash:/etc/postfix/virtual_domains" \
    "transport_maps = hash:/etc/postfix/phpanel-hold, hash:/etc/postfix/phpanel-relay" \
    "relay_domains = hash:/etc/postfix/phpanel-relay" \
    "virtual_mailbox_maps = hash:/etc/postfix/vmailbox" \
    "virtual_alias_maps = hash:/etc/postfix/valiases" \
    "smtpd_sender_login_maps = hash:/etc/postfix/vsenders" \
    "smtpd_recipient_restrictions = check_policy_service { unix:private/quota-status, timeout=10s, default_action=DUNNO }" \
    "virtual_transport = lmtp:unix:private/dovecot-lmtp" \
    "smtpd_milters = inet:127.0.0.1:11332" \
    "non_smtpd_milters = inet:127.0.0.1:11332" \
    "milter_default_action = accept" \
    "milter_protocol = 6" \
    "sender_canonical_maps = socketmap:unix:srs:forward" \
    "sender_canonical_classes = envelope_sender" \
    "recipient_canonical_maps = socketmap:unix:srs:reverse" \
    "recipient_canonical_classes = envelope_recipient, header_recipient"
  # submission 587 (STARTTLS) and smtps 465, authentication only [09]
  postconf -M "submission/inet=submission inet n - y - - smtpd"
  postconf -P "submission/inet/syslog_name=postfix/submission" \
              "submission/inet/smtpd_tls_security_level=encrypt" \
              "submission/inet/smtpd_sasl_auth_enable=yes" \
              "submission/inet/smtpd_sender_restrictions=reject_authenticated_sender_login_mismatch" \
              "submission/inet/smtpd_client_restrictions=permit_sasl_authenticated,reject"
  postconf -M "smtps/inet=smtps inet n - y - - smtpd"
  postconf -P "smtps/inet/syslog_name=postfix/smtps" \
              "smtps/inet/smtpd_tls_wrappermode=yes" \
              "smtps/inet/smtpd_sasl_auth_enable=yes" \
              "smtps/inet/smtpd_sender_restrictions=reject_authenticated_sender_login_mismatch" \
              "smtps/inet/smtpd_client_restrictions=permit_sasl_authenticated,reject"
  echo "$host" >/etc/mailname
  # postsrsd 2.x: without srs-domain its worker dies and Postfix gets "unexpected disconnect" [32]
  if [[ -f /etc/postsrsd.conf ]]; then
    sed -i "s/^#\?srs-domain *=.*/srs-domain = \"$host\"/" /etc/postsrsd.conf
    # Mail sent by the hosted domains themselves must keep its sender (SPF and DMARC alignment), so PostSRSd
    # has to know every hosted domain as local. The panel keeps this list up to date.
    [[ -s /etc/postsrsd.domains ]] || printf '%s\n' "$host" >/etc/postsrsd.domains
    if ! grep -q '^domains-file' /etc/postsrsd.conf; then
      sed -i '/^domains *=/d' /etc/postsrsd.conf
      printf 'domains-file = "/etc/postsrsd.domains"\n' >>/etc/postsrsd.conf
    fi
    systemctl restart postsrsd >>"$PHPANEL_LOG_FILE" 2>&1 || true
  fi
  if postfix check >>"$PHPANEL_LOG_FILE" 2>&1; then ok "postfix check OK ($host)"; else error "postfix check failed (see $PHPANEL_LOG_FILE)"; fi
}

setup_rspamd() {
  have rspamd || { info "rspamd not installed, skipping"; return 0; }
  [[ $DRY_RUN == 1 ]] && { info "[dry-run] configuring Rspamd"; return 0; }
  install -d -o _rspamd -g _rspamd -m 750 /var/lib/rspamd/dkim 2>/dev/null || install -d -m 750 /var/lib/rspamd/dkim
  # a running Rspamd keeps the configuration it started with; remember what it had to tell whether it must read it again
  local before after
  before=$(cat /etc/rspamd/local.d/* 2>/dev/null | sha256sum)
  write_file /etc/rspamd/local.d/redis.conf <<'CONF'
servers = "127.0.0.1:6379";
CONF
  # DKIM: keys are generated per domain by the panel (rspamadm dkim_keygen), selector 'default' [15]
  write_file /etc/rspamd/local.d/dkim_signing.conf <<'CONF'
path = "/var/lib/rspamd/dkim/$domain.$selector.key";
selector = "default";
use_domain = "header";
# the key of a domain is named after the domain itself, also when it is a subdomain (demo.example.com, not example.com)
use_esld = false;
allow_username_mismatch = true;
sign_authenticated = true;
sign_local = true;
CONF
  # "X-Spam: Yes" on spam (and any such header sent by others is removed first): the Sieve rule files it to Junk [32]
  write_file /etc/rspamd/local.d/milter_headers.conf <<'CONF'
extended_spam_headers = true;
use = ["x-spamd-result", "x-rspamd-server", "authentication-results", "spam-header"];
routines {
  spam-header {
    header = "X-Spam";
    value = "Yes";
    remove = 0;
  }
}
CONF
  # sending limit per mailbox [28]; the panel rewrites this file with the limits of the packages
  [[ -s /etc/rspamd/local.d/ratelimit.conf ]] || write_file /etc/rspamd/local.d/ratelimit.conf <<'CONF'
# Generated by PH-PANEL: sending limits per authenticated account
rates {
  ph_default = { selector = "user.lower"; bucket = { burst = 200; rate = "200 / 1h"; } }
}
CONF
  write_file /etc/rspamd/local.d/neural.conf <<CONF
enabled = $(pick false false true true);
CONF
  # LLM: Off by default [05]; the mode is changed from the panel
  if [[ ! -s /etc/rspamd/local.d/worker-controller.inc ]]; then
    local pw hash; pw=$(openssl rand -hex 12)
    hash=$(rspamadm pw -p "$pw" 2>/dev/null | tail -1)
    install -d -m 700 /root/.phpanel
    printf 'rspamd_controller_password=%s\n' "$pw" >/root/.phpanel/rspamd.txt; chmod 600 /root/.phpanel/rspamd.txt
    printf 'bind_socket = "127.0.0.1:11334";\npassword = "%s";\n' "$hash" >/etc/rspamd/local.d/worker-controller.inc
  fi
  if rspamadm configtest >>"$PHPANEL_LOG_FILE" 2>&1; then
    ok "rspamadm configtest OK"
    after=$(cat /etc/rspamd/local.d/* 2>/dev/null | sha256sum)
    # without this, a changed rule (for example how DKIM keys are found) only applied after the next restart of Rspamd
    if [[ $before != "$after" ]] && systemctl is-active --quiet rspamd; then
      if systemctl reload rspamd >>"$PHPANEL_LOG_FILE" 2>&1 || systemctl restart rspamd >>"$PHPANEL_LOG_FILE" 2>&1; then ok "Rspamd reads its changed configuration"; else warn "Rspamd could not be reloaded (see $PHPANEL_LOG_FILE)"; fi
    fi
  else error "rspamadm configtest failed (see $PHPANEL_LOG_FILE)"; fi
}

step_08_mail() {
  if dns_only; then info "dns-only: no mail"; return 0; fi
  ensure_selfsigned /opt/phpanel/ssl/server "$(mail_hostname)" \
    "DNS:$(mail_hostname)${IP_LOCAL:+,IP:$IP_LOCAL}${IP_PUBLIC:+,IP:$IP_PUBLIC}"
  setup_dovecot
  setup_postfix
  setup_rspamd
}
