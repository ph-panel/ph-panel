setup_postfix() {
  have postconf || { info "postfix not installed, skipping"; return 0; }
  [[ $DRY_RUN == 1 ]] && { info "[dry-run] configuring Postfix"; return 0; }
  local host; host=$(mail_hostname)
  local f
  for f in virtual_domains vmailbox valiases vsenders phpanel-hold phpanel-relay phpanel-sysalias; do [[ -f /etc/postfix/$f ]] || : >/etc/postfix/$f; postmap "/etc/postfix/$f"; done
  # certificates the accounts installed for their mail host [68]: the panel writes this map (certificate and key files by host name);
  # postmap -F stores the files themselves in it, so it stays root only
  [[ -f /etc/postfix/phpanel-sni ]] || : >/etc/postfix/phpanel-sni
  chmod 600 /etc/postfix/phpanel-sni
  postmap -F hash:/etc/postfix/phpanel-sni && chmod 600 /etc/postfix/phpanel-sni.db
  # domains whose mail leaves from their own address [20]: the panel writes this map and one transport per address in master.cf
  [[ -f /etc/postfix/phpanel-ipmap ]] || printf '# Generated by PH-PANEL [20]: mail of these domains leaves from their own address.\n' >/etc/postfix/phpanel-ipmap
  postmap hash:/etc/postfix/phpanel-ipmap
  # PostSRSd 2.x (Ubuntu 26.04) answers on a socketmap; 1.x (Ubuntu 24.04, Debian 12 and 13) on two TCP ports
  local srs_fwd=socketmap:unix:srs:forward srs_rev=socketmap:unix:srs:reverse
  if [[ ! -f /etc/postsrsd.conf ]]; then srs_fwd=tcp:127.0.0.1:10001; srs_rev=tcp:127.0.0.1:10002; fi
  local cert=/opt/phpanel/ssl/server
  postconf -e \
    "myhostname = $host" \
    "mydestination = \$myhostname, localhost" \
    "smtpd_banner = \$myhostname ESMTP" \
    "message_size_limit = 52428800" \
    "smtpd_tls_cert_file = $cert/fullchain.pem" \
    "smtpd_tls_key_file = $cert/privkey.pem" \
    "smtpd_tls_security_level = may" \
    "tls_server_sni_maps = hash:/etc/postfix/phpanel-sni" \
    "sender_dependent_default_transport_maps = hash:/etc/postfix/phpanel-ipmap" \
    "smtpd_tls_auth_only = yes" \
    "smtpd_tls_protocols = >=TLSv1.2" \
    "smtp_tls_security_level = may" \
    "smtpd_sasl_type = dovecot" \
    "smtpd_sasl_path = private/auth" \
    "smtpd_sasl_auth_enable = yes" \
    "smtpd_relay_restrictions = permit_mynetworks, permit_sasl_authenticated, reject_unauth_destination" \
    "virtual_mailbox_domains = hash:/etc/postfix/virtual_domains" \
    "transport_maps = hash:/etc/postfix/phpanel-hold, hash:/etc/postfix/phpanel-relay" \
    "relay_domains = hash:/etc/postfix/phpanel-relay" \
    "virtual_mailbox_maps = hash:/etc/postfix/vmailbox" \
    "virtual_alias_maps = hash:/etc/postfix/valiases, hash:/etc/postfix/phpanel-sysalias" \
    "smtpd_sender_login_maps = hash:/etc/postfix/vsenders" \
    "smtpd_recipient_restrictions = check_policy_service { unix:private/quota-status, timeout=10s, default_action=DUNNO }" \
    "virtual_transport = lmtp:unix:private/dovecot-lmtp" \
    "smtpd_milters = inet:127.0.0.1:11332" \
    "non_smtpd_milters = inet:127.0.0.1:11332" \
    "milter_default_action = accept" \
    "milter_protocol = 6" \
    "sender_canonical_maps = $srs_fwd" \
    "sender_canonical_classes = envelope_sender" \
    "recipient_canonical_maps = $srs_rev" \
    "recipient_canonical_classes = envelope_recipient, header_recipient"
  # submission 587 (STARTTLS) and smtps 465, authentication only [09]
  postconf -M "submission/inet=submission inet n - y - - smtpd"
  postconf -P "submission/inet/syslog_name=postfix/submission" \
              "submission/inet/smtpd_tls_security_level=encrypt" \
              "submission/inet/smtpd_sasl_auth_enable=yes" \
              "submission/inet/smtpd_sender_restrictions=reject_authenticated_sender_login_mismatch" \
              "submission/inet/smtpd_client_restrictions=permit_sasl_authenticated,reject"
  postconf -M "smtps/inet=smtps inet n - y - - smtpd"
  postconf -P "smtps/inet/syslog_name=postfix/smtps" \
              "smtps/inet/smtpd_tls_wrappermode=yes" \
              "smtps/inet/smtpd_sasl_auth_enable=yes" \
              "smtps/inet/smtpd_sender_restrictions=reject_authenticated_sender_login_mismatch" \
              "smtps/inet/smtpd_client_restrictions=permit_sasl_authenticated,reject"
  echo "$host" >/etc/mailname
  # postsrsd 2.x: without srs-domain its worker dies and Postfix gets "unexpected disconnect" [32]
  if [[ -f /etc/postsrsd.conf ]]; then
    sed -i "s/^#\?srs-domain *=.*/srs-domain = \"$host\"/" /etc/postsrsd.conf
    # Mail sent by the hosted domains themselves must keep its sender (SPF and DMARC alignment), so PostSRSd
    # has to know every hosted domain as local. The panel keeps this list up to date.
    [[ -s /etc/postsrsd.domains ]] || printf '%s\n' "$host" >/etc/postsrsd.domains
    if ! grep -q '^domains-file' /etc/postsrsd.conf; then
      sed -i '/^domains *=/d' /etc/postsrsd.conf
      printf 'domains-file = "/etc/postsrsd.domains"\n' >>/etc/postsrsd.conf
    fi
    systemctl restart postsrsd >>"$PHPANEL_LOG_FILE" 2>&1 || true
  elif [[ -f /etc/default/postsrsd ]]; then
    # postsrsd 1.x: the rewriting domain and the local domains (never rewritten) come from its defaults file, read by its launcher;
    # the panel keeps SRS_EXCLUDE_DOMAINS up to date with the hosted domains
    [[ -s /etc/postsrsd.domains ]] || printf '%s\n' "$host" >/etc/postsrsd.domains
    local excl; excl=$(paste -sd, /etc/postsrsd.domains)
    local kv k v
    for kv in "SRS_DOMAIN=$host" "SRS_EXCLUDE_DOMAINS=$excl"; do
      k=${kv%%=*}; v=${kv#*=}
      if grep -q "^$k=" /etc/default/postsrsd; then sed -i "s|^$k=.*|$k=\"$v\"|" /etc/default/postsrsd; else printf '%s="%s"\n' "$k" "$v" >>/etc/default/postsrsd; fi
    done
    systemctl restart postsrsd >>"$PHPANEL_LOG_FILE" 2>&1 || true
  fi
  # SMTP login for the optional SMTP account of system mail [46] (PLAIN and LOGIN come from this package); an update installs it too
  if ! dpkg -s libsasl2-modules >/dev/null 2>&1; then
    DEBIAN_FRONTEND=noninteractive apt-get install -y libsasl2-modules >>"$PHPANEL_LOG_FILE" 2>&1 || warn "libsasl2-modules could not be installed: an SMTP account for system mail will not work until it is"
  fi
  if postfix check >>"$PHPANEL_LOG_FILE" 2>&1; then ok "postfix check OK ($host)"; else error "postfix check failed (see $PHPANEL_LOG_FILE)"; fi
}

setup_rspamd() {
  have rspamd || { info "rspamd not installed, skipping"; return 0; }
  [[ $DRY_RUN == 1 ]] && { info "[dry-run] configuring Rspamd"; return 0; }
  install -d -o _rspamd -g _rspamd -m 750 /var/lib/rspamd/dkim 2>/dev/null || install -d -m 750 /var/lib/rspamd/dkim
  # a running Rspamd keeps the configuration it started with; remember what it had to tell whether it must read it again
  local before after tcp_ctl=0
  before=$(cat /etc/rspamd/local.d/* 2>/dev/null | sha256sum)
  # an older server still has the controller on 127.0.0.1:11334 and Redis on its TCP port: those need a restart, not a reload
  ss -ltnH 2>/dev/null | grep -qE '127\.0\.0\.1:11334\b' && tcp_ctl=1
  # Rspamd uses Redis when it is installed; without it the file says so and Rspamd runs without Redis (Software and services keeps it in step)
  if [[ -x /usr/bin/redis-server ]]; then
    write_file /etc/rspamd/local.d/redis.conf <<'CONF'
servers = "/run/redis/redis-server.sock";
CONF
    # the socket is for the redis group: Rspamd's user joins it (takes effect when Rspamd restarts)
    getent group redis >/dev/null 2>&1 && usermod -aG redis _rspamd 2>/dev/null || true
  else
    write_file /etc/rspamd/local.d/redis.conf <<'CONF'
# Generated by PH-PANEL: Redis is not installed or is stopped, so Rspamd runs without it.
# Software and services (Admin) puts the server line back when Redis returns.
CONF
  fi
  # DKIM: keys are generated per domain by the panel (rspamadm dkim_keygen), selector 'default' [15]
  write_file /etc/rspamd/local.d/dkim_signing.conf <<'CONF'
path = "/var/lib/rspamd/dkim/$domain.$selector.key";
selector = "default";
use_domain = "header";
# the key of a domain is named after the domain itself, also when it is a subdomain (demo.example.com, not example.com)
use_esld = false;
allow_username_mismatch = true;
sign_authenticated = true;
sign_local = true;
CONF
  # DKIM of the server's own name: system mail (cron output, alerts, notifications, tests) is signed as <host name>, so receivers that
  # require SPF or DKIM (Gmail) can verify it. The key is created once and never replaced; its public half is shown on Admin > Mail.
  local mh; mh=$(mail_hostname)
  if [[ $mh == *.* && ! -s /var/lib/rspamd/dkim/$mh.default.key ]] && have rspamadm; then
    if rspamadm dkim_keygen -d "$mh" -s default -b 2048 -k "/var/lib/rspamd/dkim/$mh.default.key" >/dev/null 2>>"$PHPANEL_LOG_FILE"; then
      chown root:_rspamd "/var/lib/rspamd/dkim/$mh.default.key" 2>/dev/null || true
      chmod 640 "/var/lib/rspamd/dkim/$mh.default.key"
      ok "DKIM key created for the server name $mh"
    else warn "the DKIM key of the server name could not be created"; fi
  fi
  # "X-Spam: Yes" on spam (and any such header sent by others is removed first): the Sieve rule files it to Junk [32]
  write_file /etc/rspamd/local.d/milter_headers.conf <<'CONF'
extended_spam_headers = true;
use = ["x-spamd-result", "x-rspamd-server", "authentication-results", "spam-header"];
routines {
  spam-header {
    header = "X-Spam";
    value = "Yes";
    remove = 0;
  }
}
CONF
  # sending limit per mailbox [28]; the panel rewrites this file with the limits of the packages
  [[ -s /etc/rspamd/local.d/ratelimit.conf ]] || write_file /etc/rspamd/local.d/ratelimit.conf <<'CONF'
# Generated by PH-PANEL: sending limits per authenticated account
rates {
  ph_default = { selector = "user.lower"; bucket = { burst = 200; rate = "200 / 1h"; } }
}
CONF
  # spam thresholds [63]: Junk from 6, refuse from 15, greylisting off (a threshold nothing reaches); the panel rewrites both files from the
  # settings of the server, the accounts and the mailboxes (settings.conf holds the per-mailbox entries)
  [[ -s /etc/rspamd/local.d/actions.conf ]] || write_file /etc/rspamd/local.d/actions.conf <<'CONF'
# Generated by PH-PANEL [63]: the spam thresholds of every mailbox without settings of its own. Changes are overwritten.
reject = 15;
add_header = 6;
greylist = 1000000;
CONF
  [[ -e /etc/rspamd/local.d/settings.conf ]] || write_file /etc/rspamd/local.d/settings.conf <<'CONF'
# Generated by PH-PANEL [63]: spam settings per mailbox (Rspamd settings module). Changes are overwritten.
CONF
  write_file /etc/rspamd/local.d/neural.conf <<CONF
enabled = $(pick false false true true);
CONF
  # LLM: Off by default [05]; the mode is changed from the panel
  # The controller (web interface and statistics) has no TCP port: a unix socket for the rspamd user, and it asks for its password
  # also from this machine. The file with the password hash is not world-readable.
  local ctl_sock='/run/rspamd/controller.sock mode=0660 owner=_rspamd group=_rspamd'
  if [[ ! -s /etc/rspamd/local.d/worker-controller.inc || ! -s /root/.phpanel/rspamd.txt ]]; then
    local pw hash; pw=$(openssl rand -hex 12)
    hash=$(rspamadm pw -p "$pw" 2>/dev/null | tail -1)
    install -d -m 700 /root/.phpanel
    printf 'rspamd_controller_password=%s\n' "$pw" >/root/.phpanel/rspamd.txt; chmod 600 /root/.phpanel/rspamd.txt
    printf 'bind_socket = "%s";\npassword = "%s";\n' "$ctl_sock" "$hash" >/etc/rspamd/local.d/worker-controller.inc
  elif ! grep -q 'controller.sock' /etc/rspamd/local.d/worker-controller.inc; then
    # an existing server: keep the password, move the listener off the TCP port
    local keep; keep=$(grep -E '^password' /etc/rspamd/local.d/worker-controller.inc | head -1)
    printf 'bind_socket = "%s";\n%s\n' "$ctl_sock" "$keep" >/etc/rspamd/local.d/worker-controller.inc
  fi
  chown root:_rspamd /etc/rspamd/local.d/worker-controller.inc 2>/dev/null || true
  chmod 640 /etc/rspamd/local.d/worker-controller.inc
  # no address counts as "secure" (a controller request without the password is refused even from this machine)
  write_file /etc/rspamd/override.d/worker-controller.inc 640 <<'CONF'
# Generated by PH-PANEL: the controller needs its password from every client
secure_ip = [];
CONF
  chown root:_rspamd /etc/rspamd/override.d/worker-controller.inc 2>/dev/null || true
  if rspamadm configtest >>"$PHPANEL_LOG_FILE" 2>&1; then
    ok "rspamadm configtest OK"
    after=$(cat /etc/rspamd/local.d/* 2>/dev/null | sha256sum)
    # without this, a changed rule (for example how DKIM keys are found) only applied after the next restart of Rspamd
    if [[ $tcp_ctl == 1 ]] && systemctl is-active --quiet rspamd; then
      if systemctl restart rspamd >>"$PHPANEL_LOG_FILE" 2>&1; then ok "Rspamd restarted: its controller and Redis are on private sockets now"; else warn "Rspamd could not be restarted (see $PHPANEL_LOG_FILE)"; fi
    elif [[ $before != "$after" ]] && systemctl is-active --quiet rspamd; then
      if systemctl reload rspamd >>"$PHPANEL_LOG_FILE" 2>&1 || systemctl restart rspamd >>"$PHPANEL_LOG_FILE" 2>&1; then ok "Rspamd reads its changed configuration"; else warn "Rspamd could not be reloaded (see $PHPANEL_LOG_FILE)"; fi
    fi
  else error "rspamadm configtest failed (see $PHPANEL_LOG_FILE)"; fi
}

# The lists of mailboxes, forwarders, senders and domains of all accounts are for root and Postfix only (the panel writes them the same way).
lock_postfix_maps() {
  [[ $DRY_RUN == 1 ]] && return 0
  local f
  for f in vmailbox valiases vsenders virtual_domains phpanel-hold phpanel-relay phpanel-ipmap phpanel-sysalias; do
    [[ -e /etc/postfix/$f ]] && { chgrp postfix "/etc/postfix/$f" 2>/dev/null; chmod 640 "/etc/postfix/$f"; }
    [[ -e /etc/postfix/$f.db ]] && { chgrp postfix "/etc/postfix/$f.db" 2>/dev/null; chmod 640 "/etc/postfix/$f.db"; }
  done
  return 0
}

step_08_mail() {
  if dns_only; then info "dns-only: no mail"; return 0; fi
  ensure_selfsigned /opt/phpanel/ssl/server "$(mail_hostname)" \
    "DNS:$(mail_hostname)${IP_LOCAL:+,IP:$IP_LOCAL}${IP_PUBLIC:+,IP:$IP_PUBLIC}"
  setup_dovecot
  setup_postfix
  lock_postfix_maps
  # a listener's permission is applied when Dovecot starts: an older server still has the stock open lmtp socket
  if [[ $DRY_RUN != 1 && -S /run/dovecot/lmtp && $(stat -c %a /run/dovecot/lmtp 2>/dev/null) != 600 ]] && systemctl is-active --quiet dovecot; then
    run systemctl restart dovecot && ok "Dovecot restarted: its lmtp socket is closed to hosting accounts" || warn "Dovecot did not restart"
  fi
  setup_rspamd
}
