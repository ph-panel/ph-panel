#!/usr/bin/env bash
# Step 08 – mail: Postfix, Dovecot 2.4, Rspamd, SRS [05][31]-[34]. Configuration only;
# users and virtual domains come from the panel (the files below start out empty).

mail_hostname() { echo "${PANEL_HOSTNAME:-$(hostname -f 2>/dev/null || hostname)}"; }

setup_dovecot() {
  have doveconf || { info "dovecot not installed, skipping"; return 0; }
  [[ $DRY_RUN == 1 ]] && { info "[dry-run] configuring Dovecot"; return 0; }
  # no PAM authentication: users are virtual, in a passwd-file generated from the DB [F2]
  sed -i 's/^!include auth-system.conf.ext/#!include auth-system.conf.ext/' /etc/dovecot/conf.d/10-auth.conf
  [[ -f /etc/dovecot/phpanel-users ]] || : >/etc/dovecot/phpanel-users
  chown root:dovecot /etc/dovecot/phpanel-users; chmod 640 /etc/dovecot/phpanel-users
  write_file /etc/dovecot/local.conf <<'CONF'
# Generated by PH-PANEL. Dovecot 2.4 syntax.
mail_driver = maildir
mail_path = %{home}/Maildir
mail_inbox_path =
auth_mechanisms = plain login

ssl_server {
  cert_file = /opt/phpanel/ssl/server/fullchain.pem
  key_file = /opt/phpanel/ssl/server/privkey.pem
}

passdb passwd-file {
  passwd_file_path = /etc/dovecot/phpanel-users
  default_password_scheme = SHA512-CRYPT
}
userdb passwd-file {
  passwd_file_path = /etc/dovecot/phpanel-users
  fields {
    home = %{userdb:home}
  }
}

# the full address is the username (virtual domains)
protocol lmtp {
  auth_username_format = %{user | lower}
}

service auth {
  unix_listener /var/spool/postfix/private/auth {
    mode = 0660
    user = postfix
    group = postfix
  }
}
service lmtp {
  unix_listener /var/spool/postfix/private/dovecot-lmtp {
    mode = 0600
    user = postfix
    group = postfix
  }
}
service managesieve-login {
  inet_listener sieve {
    port = 4190
  }
  inet_listener sieve_deprecated {
    port = 0
  }
}
CONF
  if doveconf -n >/dev/null 2>>"$PHPANEL_LOG_FILE"; then ok "Dovecot configuration valid"; else error "doveconf found errors (see $PHPANEL_LOG_FILE)"; fi
}

setup_postfix() {
  have postconf || { info "postfix not installed, skipping"; return 0; }
  [[ $DRY_RUN == 1 ]] && { info "[dry-run] configuring Postfix"; return 0; }
  local host; host=$(mail_hostname)
  local f
  for f in virtual_domains vmailbox; do [[ -f /etc/postfix/$f ]] || : >/etc/postfix/$f; postmap "/etc/postfix/$f"; done
  local cert=/opt/phpanel/ssl/server
  postconf -e \
    "myhostname = $host" \
    "mydestination = \$myhostname, localhost" \
    "smtpd_banner = \$myhostname ESMTP" \
    "message_size_limit = 52428800" \
    "smtpd_tls_cert_file = $cert/fullchain.pem" \
    "smtpd_tls_key_file = $cert/privkey.pem" \
    "smtpd_tls_security_level = may" \
    "smtpd_tls_auth_only = yes" \
    "smtpd_tls_protocols = >=TLSv1.2" \
    "smtp_tls_security_level = may" \
    "smtpd_sasl_type = dovecot" \
    "smtpd_sasl_path = private/auth" \
    "smtpd_sasl_auth_enable = yes" \
    "smtpd_relay_restrictions = permit_mynetworks, permit_sasl_authenticated, reject_unauth_destination" \
    "virtual_mailbox_domains = hash:/etc/postfix/virtual_domains" \
    "virtual_mailbox_maps = hash:/etc/postfix/vmailbox" \
    "virtual_transport = lmtp:unix:private/dovecot-lmtp" \
    "smtpd_milters = inet:127.0.0.1:11332" \
    "non_smtpd_milters = inet:127.0.0.1:11332" \
    "milter_default_action = accept" \
    "milter_protocol = 6" \
    "sender_canonical_maps = socketmap:unix:srs:forward" \
    "sender_canonical_classes = envelope_sender" \
    "recipient_canonical_maps = socketmap:unix:srs:reverse" \
    "recipient_canonical_classes = envelope_recipient, header_recipient"
  # submission 587 (STARTTLS) and smtps 465, authentication only [09]
  postconf -M "submission/inet=submission inet n - y - - smtpd"
  postconf -P "submission/inet/syslog_name=postfix/submission" \
              "submission/inet/smtpd_tls_security_level=encrypt" \
              "submission/inet/smtpd_sasl_auth_enable=yes" \
              "submission/inet/smtpd_client_restrictions=permit_sasl_authenticated,reject"
  postconf -M "smtps/inet=smtps inet n - y - - smtpd"
  postconf -P "smtps/inet/syslog_name=postfix/smtps" \
              "smtps/inet/smtpd_tls_wrappermode=yes" \
              "smtps/inet/smtpd_sasl_auth_enable=yes" \
              "smtps/inet/smtpd_client_restrictions=permit_sasl_authenticated,reject"
  echo "$host" >/etc/mailname
  # postsrsd 2.x: without srs-domain its worker dies and Postfix gets "unexpected disconnect" [32]
  if [[ -f /etc/postsrsd.conf ]]; then
    sed -i "s/^#\?srs-domain *=.*/srs-domain = \"$host\"/" /etc/postsrsd.conf
  fi
  if postfix check >>"$PHPANEL_LOG_FILE" 2>&1; then ok "postfix check OK ($host)"; else error "postfix check failed (see $PHPANEL_LOG_FILE)"; fi
}

setup_rspamd() {
  have rspamd || { info "rspamd not installed, skipping"; return 0; }
  [[ $DRY_RUN == 1 ]] && { info "[dry-run] configuring Rspamd"; return 0; }
  install -d -o _rspamd -g _rspamd -m 750 /var/lib/rspamd/dkim 2>/dev/null || install -d -m 750 /var/lib/rspamd/dkim
  write_file /etc/rspamd/local.d/redis.conf <<'CONF'
servers = "127.0.0.1:6379";
CONF
  # DKIM: keys are generated per domain by the panel (rspamadm dkim_keygen), selector 'default' [15]
  write_file /etc/rspamd/local.d/dkim_signing.conf <<'CONF'
path = "/var/lib/rspamd/dkim/$domain.$selector.key";
selector = "default";
use_domain = "header";
allow_username_mismatch = true;
sign_authenticated = true;
sign_local = true;
CONF
  write_file /etc/rspamd/local.d/milter_headers.conf <<'CONF'
extended_spam_headers = true;
use = ["x-spamd-result", "x-rspamd-server", "authentication-results"];
CONF
  write_file /etc/rspamd/local.d/neural.conf <<CONF
enabled = $(pick false false true true);
CONF
  # LLM: Off by default [05]; the mode is changed from the panel
  if [[ ! -s /etc/rspamd/local.d/worker-controller.inc ]]; then
    local pw hash; pw=$(openssl rand -hex 12)
    hash=$(rspamadm pw -p "$pw" 2>/dev/null | tail -1)
    install -d -m 700 /root/.phpanel
    printf 'rspamd_controller_password=%s\n' "$pw" >/root/.phpanel/rspamd.txt; chmod 600 /root/.phpanel/rspamd.txt
    printf 'bind_socket = "127.0.0.1:11334";\npassword = "%s";\n' "$hash" >/etc/rspamd/local.d/worker-controller.inc
  fi
  if rspamadm configtest >>"$PHPANEL_LOG_FILE" 2>&1; then ok "rspamadm configtest OK"; else error "rspamadm configtest failed (see $PHPANEL_LOG_FILE)"; fi
}

step_08_mail() {
  ensure_selfsigned /opt/phpanel/ssl/server "$(mail_hostname)" \
    "DNS:$(mail_hostname)${IP_LOCAL:+,IP:$IP_LOCAL}${IP_PUBLIC:+,IP:$IP_PUBLIC}"
  setup_dovecot
  setup_postfix
  setup_rspamd
}
