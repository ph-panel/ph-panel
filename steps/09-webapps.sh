# ph-signon.php: redeems the one-time token from the panel over the local socket and opens the sign-on session.
install_pma_signon() {
  local dir=$1
  write_file "$dir/ph-signon.php" 640 <<'PHP'
<?php
// Generated by PH-PANEL [37]: signs a user in to phpMyAdmin with the one-time token handed over by the panel.
declare(strict_types=1);
ini_set('display_errors', '0');

const PH_SOCKET = '/run/phpanel/public.sock';
const PH_SESSIONS = '/opt/phpanel/dbadmin/sessions';
const PH_PATH = '/phpmyadmin/';

header('Cache-Control: no-store');
header('Referrer-Policy: no-referrer');
header('X-Content-Type-Options: nosniff');
header('X-Frame-Options: DENY');

function ph_panel_url(): string
{
    $host = (string) ($_SERVER['HTTP_HOST'] ?? '');
    $host = preg_replace('/:\d+$/', '', $host) ?? '';
    if (preg_match('/^[A-Za-z0-9.-]{1,253}$/', $host) === 1 || preg_match('/^\[[0-9A-Fa-f:]{2,45}\]$/', $host) === 1) {
        return 'https://' . $host . ':8443/databases';
    }
    return '/';
}

function ph_call(string $path, array $body): ?array
{
    if (!function_exists('curl_init')) {
        return null;
    }
    $ch = curl_init('http://localhost' . $path);
    curl_setopt_array($ch, [
        CURLOPT_UNIX_SOCKET_PATH => PH_SOCKET,
        CURLOPT_POST => true,
        CURLOPT_POSTFIELDS => json_encode($body),
        CURLOPT_HTTPHEADER => ['Content-Type: application/json'],
        CURLOPT_RETURNTRANSFER => true,
        CURLOPT_CONNECTTIMEOUT => 3,
        CURLOPT_TIMEOUT => 8,
    ]);
    $out = curl_exec($ch);
    curl_close($ch);
    if ($out === false) {
        return null;
    }
    $j = json_decode((string) $out, true);
    return is_array($j) ? $j : [];
}

function ph_cookie_params(): array
{
    return ['path' => PH_PATH, 'secure' => true, 'httponly' => true, 'samesite' => 'Lax'];
}

function ph_clear_cookies(): void
{
    foreach (['PhSignon', 'PhPmaSid'] as $name) {
        setcookie($name, '', ['expires' => 1] + ph_cookie_params());
    }
}

function ph_session(): void
{
    session_save_path(PH_SESSIONS);
    ini_set('session.gc_maxlifetime', '3900');
    session_name('PhSignon');
    session_set_cookie_params(['lifetime' => 0] + ph_cookie_params());
}

function ph_page(int $status, string $kind): never
