install_phpmyadmin() {
  local ver dir=/opt/phpanel/dbadmin/phpmyadmin base=https://files.phpmyadmin.net/phpMyAdmin sum
  ver=$(curl -fsSL --max-time 20 https://www.phpmyadmin.net/home_page/version.json 2>/dev/null | jq -r '.version' 2>/dev/null) || ver=
  [[ $ver =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || { error "could not determine the phpMyAdmin version"; return 0; }
  if [[ -f $dir/.phpanel-version && $(cat "$dir/.phpanel-version") == "$ver" ]]; then ok "phpMyAdmin $ver already installed"; else
    sum=$(curl -fsSL --max-time 20 "$base/$ver/phpMyAdmin-$ver-all-languages.tar.gz.sha256" 2>/dev/null | awk '{print $1}') || sum=
    [[ -n $sum ]] || { error "the official phpMyAdmin $ver checksum is missing"; return 0; }
    fetch_archive "$base/$ver/phpMyAdmin-$ver-all-languages.tar.gz" "$dir" "$sum" \
      || { error "downloading phpMyAdmin $ver failed"; return 0; }
    echo "$ver" >"$dir/.phpanel-version"
    ok "phpMyAdmin $ver installed (official checksum verified)"
  fi
  local bf; bf=$(grep -oP "blowfish_secret'\] = '\K[^']+" "$dir/config.inc.php" 2>/dev/null || true)
  [[ -n $bf ]] || bf=$(openssl rand -hex 16)
  install -d -o dbadmin -g dbadmin -m 750 /opt/phpanel/dbadmin/tmp /opt/phpanel/dbadmin/sessions
  install_pma_signon "$dir"
  write_file "$dir/config.inc.php" 640 <<CONF
<?php
// Generated by PH-PANEL [37]. A session opened from the panel signs in with a temporary database user (sign-on);
// without one, users sign in with a database user and its password (cookie).
\$cfg['blowfish_secret'] = '$bf';
\$cfg['SessionSavePath'] = '/opt/phpanel/dbadmin/sessions';
if (isset(\$_COOKIE['PhSignon']) && is_string(\$_COOKIE['PhSignon'])) {
    \$cfg['Servers'][1]['auth_type'] = 'signon';
    \$cfg['Servers'][1]['SignonSession'] = 'PhSignon';
    \$cfg['Servers'][1]['SignonCookieParams'] = ['lifetime' => 0, 'path' => '/phpmyadmin/', 'secure' => true, 'httponly' => true, 'samesite' => 'Lax'];
    \$cfg['Servers'][1]['SignonURL'] = '/phpmyadmin/ph-signon.php';
    \$cfg['Servers'][1]['LogoutURL'] = '/phpmyadmin/ph-signon.php?bye=1';
} else {
    \$cfg['Servers'][1]['auth_type'] = 'cookie';
}
\$cfg['Servers'][1]['host'] = '127.0.0.1';
\$cfg['Servers'][1]['AllowNoPassword'] = false;
\$cfg['Servers'][1]['AllowRoot'] = false;
\$cfg['TempDir'] = '/opt/phpanel/dbadmin/tmp';
\$cfg['VersionCheck'] = false;
// failed sign-ins go to the system log, where Fail2Ban reads them; the real client address comes from Caddy
\$cfg['AuthLog'] = 'syslog';
\$cfg['TrustedProxies'] = ['127.0.0.1' => 'X-Forwarded-For'];
\$cfg['LoginCookieValidity'] = 3600;
ini_set('session.gc_maxlifetime', '3900');
\$cfg['LoginCookieStore'] = 0;
\$cfg['ShowPhpInfo'] = false;
CONF
  chown -R root:dbadmin "$dir"; chmod -R g+rX,o-rwx "$dir"
}

setup_webapps_caddy() {
  install -d -m 755 /opt/phpanel/caddy
  # shared snippet: phpMyAdmin under /phpmyadmin/, without the directories that must never be served [37]
  write_file /opt/phpanel/caddy/00-snippets.caddy <<'CONF'
(phpmyadmin) {
	@pma_blocked path_regexp pmab (?i)^/phpmyadmin/(setup|libraries|templates|vendor|sql|locale|doc|examples|tmp)(/|$)|^/phpmyadmin/(composer\.(json|lock)|config\.inc\.php|README|ChangeLog|LICENSE|RELEASE-DATE.*|CONTRIBUTING.*|package\.json|yarn\.lock)$
	redir /phpmyadmin /phpmyadmin/ permanent
	handle @pma_blocked {
		respond 403
	}
	handle /phpmyadmin/* {
		header {
			X-Frame-Options SAMEORIGIN
			X-Content-Type-Options nosniff
			Referrer-Policy same-origin
		}
		root * /opt/phpanel/dbadmin
		php_fastcgi unix//run/php/phpanel-dbadmin.sock
		file_server
	}
}
CONF
  # phpMyAdmin on the server's own addresses, only for installs without a panel hostname
  local ips=() ip
  for ip in ${IP_LOCAL:-} ${IP_PUBLIC:-}; do
    [[ -n $ip && " ${ips[*]} " != *" $ip "* ]] && ips+=("$ip")
  done
  if [[ -n ${PANEL_HOSTNAME:-} ]]; then
    # a panel hostname exists: phpMyAdmin lives only there, so the by-IP site is not needed (and is removed)
    rm -f /opt/phpanel/caddy/15-phpmyadmin-ip.caddy
  elif [[ ${#ips[@]} -gt 0 ]]; then
    local names; names=$(printf 'https://%s, ' "${ips[@]}"); names=${names%, }
    write_file /opt/phpanel/caddy/15-phpmyadmin-ip.caddy <<CONF
# Generated by PH-PANEL [37]: phpMyAdmin by IP address (internal certificate); everything else goes to the panel
$names {
	tls internal
	import phpmyadmin
	handle {
		redir https://{host}:8443{uri} temporary
	}
}
CONF
  fi
  # local diagnostic site, loopback only; the public addresses (mail.<domain>/webmail) come from the panel DB [25]
  write_file /opt/phpanel/caddy/20-webapps-local.caddy <<CONF
http://127.0.0.1:8091 {
	bind 127.0.0.1
	handle_path /roundcube/* {
		root * /opt/phpanel/webmail/roundcube
		php_fastcgi unix//run/php/phpanel-webmail.sock
		file_server
	}
	handle_path /snappymail/* {
		root * /opt/phpanel/webmail/snappymail
		php_fastcgi unix//run/php/phpanel-webmail.sock
		file_server
	}
	handle_path /phpmyadmin/* {
		root * /opt/phpanel/dbadmin/phpmyadmin
		php_fastcgi unix//run/php/phpanel-dbadmin.sock
		file_server
	}
}
CONF
  if [[ $DRY_RUN != 1 ]]; then
    runuser -u caddy -- caddy validate --config /etc/caddy/Caddyfile --adapter caddyfile >>"$PHPANEL_LOG_FILE" 2>&1 \
      && ok "Caddyfile valid (with the web apps)" || error "caddy validate failed after adding the web apps"
  fi
}

step_09_webapps() {
  [[ $DRY_RUN == 1 ]] && { info "[dry-run] installing Roundcube, SnappyMail, phpMyAdmin"; return 0; }
  webapp_php_version || { error "no PHP version installed; skipping the web apps"; return 0; }
  info "php-fpm pools on PHP $WEBAPP_PHP"
  install -d -m 755 /opt/phpanel /opt/phpanel/webmail /opt/phpanel/dbadmin
  webapp_pool webmail webmail
  webapp_pool dbadmin dbadmin
  setup_pma_group
  install_roundcube
  install_snappymail
  install_webmail_sso
  install_phpmyadmin
  run systemctl restart "php${WEBAPP_PHP}-fpm" || true   # restart, not reload: the pool user has a new group
  setup_webapps_caddy
}
