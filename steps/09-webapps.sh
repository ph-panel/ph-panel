$method = (string) ($_SERVER['REQUEST_METHOD'] ?? 'GET');

if (isset($_GET['bye'])) { // logout from phpMyAdmin: end the temporary user and the sign-on session
    $sid = $_COOKIE['PhPmaSid'] ?? '';
    if (is_string($sid) && preg_match('/^[A-Za-z0-9_-]{22}$/', $sid) === 1) {
        ph_call('/pma/close', ['sid' => $sid]);
    }
    $sess = $_COOKIE['PhSignon'] ?? '';
    if (is_string($sess) && preg_match('/^[A-Za-z0-9,-]{16,128}$/', $sess) === 1) {
        ph_session();
        session_id($sess);
        session_start();
        $_SESSION = [];
        session_destroy();
    }
    ph_clear_cookies();
    ph_page(200, 'closed');
}

if ($method !== 'POST') { // opened directly, or phpMyAdmin sent an expired session here
    ph_clear_cookies();
    ph_page(200, 'direct');
}

$token = $_POST['t'] ?? '';
if (!is_string($token) || preg_match('/^[A-Za-z0-9_-]{43}$/', $token) !== 1) {
    ph_page(403, 'expired');
}
$panelSession = $_COOKIE['phpanel_session'] ?? '';
$res = ph_call('/pma/redeem', [
    'token' => $token,
    'ip' => (string) ($_SERVER['REMOTE_ADDR'] ?? ''),   // set by Caddy from the real connection; never taken from a header
    'panel_session' => is_string($panelSession) ? $panelSession : '',
]);
if ($res === null) {
    ph_page(503, 'down');
}
if (($res['ok'] ?? false) !== true || !is_string($res['user'] ?? null) || !is_string($res['password'] ?? null) || !is_string($res['sid'] ?? null)) {
    ph_page(403, 'expired');
}

unset($_COOKIE['PhSignon']); // never reuse a session id that came from the browser
ph_session();
session_start();
$_SESSION['PMA_single_signon_user'] = $res['user'];
