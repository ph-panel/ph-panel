#!/usr/bin/env bash
# Step 09 – central web apps: Roundcube and SnappyMail [25], phpMyAdmin [37].
# Installed from official archives (not from apt, to avoid pulling in dbconfig-common), in /opt/phpanel, with dedicated
# php-fpm pools in ondemand mode. Autologin (SSO) comes with the daemon.

WEBAPP_PHP=

webapp_php_version() {
  local v
  for v in 8.4 8.3 8.5 8.2; do
    [[ " ${PHP_INSTALLED:-} " == *" $v "* ]] && { WEBAPP_PHP=$v; return 0; }
  done
  WEBAPP_PHP=$(awk '{print $NF}' <<<"${PHP_INSTALLED:-}")
  [[ -n $WEBAPP_PHP ]]
}

latest_github_tag() { # latest_github_tag OWNER/REPO – without the API (rate limit), via redirect
  local t; t=$(curl -fsSLI --max-time 20 -o /dev/null -w '%{url_effective}' "https://github.com/$1/releases/latest" 2>/dev/null) || return 1
  echo "${t##*/}"
}

# fetch_archive URL DEST_DIR [SHA256] – downloads, verifies (if a hash is given), extracts with one directory level stripped
fetch_archive() {
  local url=$1 dest=$2 want=${3:-} tmp file got
  tmp=$(mktemp -d); file=$tmp/${url##*/}
  curl -fsSL --max-time 300 -o "$file" "$url" || { rm -rf "$tmp"; return 1; }
  got=$(sha256sum "$file" | awk '{print $1}')
  if [[ -n $want && $got != "$want" ]]; then error "wrong checksum for ${url##*/}"; rm -rf "$tmp"; return 1; fi
  _logfile "SHA256 ${url##*/} $got"
  rm -rf "$dest"; install -d "$dest"
  case $file in
    *.zip) unzip -q "$file" -d "$dest" ;;
    *) tar -xzf "$file" -C "$dest" --strip-components=1 ;;
  esac
  rm -rf "$tmp"
}

webapp_pool() { # webapp_pool NAME USER – ondemand php-fpm pool, own socket
  local name=$1 user=$2
  id "$user" >/dev/null 2>&1 || useradd --system --home-dir "/opt/phpanel/$name" --shell /usr/sbin/nologin "$user"
  write_file "/etc/php/$WEBAPP_PHP/fpm/pool.d/phpanel-$name.conf" <<CONF
; Generated by PH-PANEL [25][37]
[phpanel-$name]
user = $user
group = $user
listen = /run/php/phpanel-$name.sock
listen.owner = caddy
listen.group = caddy
listen.mode = 0660
pm = ondemand
pm.max_children = $(pick 3 5 10 20)
pm.process_idle_timeout = 10s
php_admin_value[open_basedir] = /opt/phpanel/$name:/opt/phpanel/webmail:/opt/phpanel/dbadmin:/tmp:/usr/share/php
php_admin_value[upload_tmp_dir] = /opt/phpanel/$name/tmp
CONF
  install -d -o "$user" -g "$user" -m 750 "/opt/phpanel/$name/tmp"
  usermod -aG "$user" caddy 2>/dev/null || true   # Caddy reads the application's static files
}

install_roundcube() {
  local tag ver dir=/opt/phpanel/webmail/roundcube
  tag=$(latest_github_tag roundcube/roundcubemail) || { error "could not determine the Roundcube version"; return 0; }
  ver=$tag
  if [[ -f $dir/.phpanel-version && $(cat "$dir/.phpanel-version") == "$ver" ]]; then ok "Roundcube $ver already installed"; else
    fetch_archive "https://github.com/roundcube/roundcubemail/releases/download/$tag/roundcubemail-$ver-complete.tar.gz" "$dir" \
      || { error "downloading Roundcube $ver failed"; return 0; }
    echo "$ver" >"$dir/.phpanel-version"
    ok "Roundcube $ver installed"
  fi
  local data=/opt/phpanel/webmail/data; install -d -o webmail -g webmail -m 750 "$data" "$data/roundcube-logs"
  local key; key=$(grep -oP "des_key'\] = '\K[^']+" "$dir/config/config.inc.php" 2>/dev/null || true)
  [[ -n $key ]] || key=$(openssl rand -hex 12)
  write_file "$dir/config/config.inc.php" 640 <<CONF
<?php
// Generated by PH-PANEL [25]
\$config['db_dsnw'] = 'sqlite:///$data/roundcube.db?mode=0640';
\$config['imap_host'] = 'tls://127.0.0.1:143';
\$config['imap_conn_options'] = ['ssl' => ['verify_peer' => false, 'verify_peer_name' => false]];
\$config['smtp_host'] = 'tls://127.0.0.1:587';
\$config['smtp_conn_options'] = ['ssl' => ['verify_peer' => false, 'verify_peer_name' => false]];
\$config['smtp_user'] = '%u';
\$config['smtp_pass'] = '%p';
\$config['username_domain'] = '';
\$config['des_key'] = '$key';
\$config['log_dir'] = '$data/roundcube-logs/';
\$config['temp_dir'] = '/opt/phpanel/webmail/tmp/';
\$config['product_name'] = 'Webmail';
\$config['plugins'] = [];
\$config['session_name'] = 'phpanel_webmail';
CONF
  install -d -o webmail -g webmail -m 750 /opt/phpanel/webmail/tmp
  chown -R root:webmail "$dir"; chmod -R g+rX,o-rwx "$dir"
  # initdb.sh can exit non-zero after creating the schema, so success means the users table exists.
  # All sqlite3 calls run as the webmail user; as root they would leave an unwritable empty file behind.
  local q="select 1 from users limit 1"
  if ! { [[ -s $data/roundcube.db ]] && runuser -u webmail -- sqlite3 "$data/roundcube.db" "$q" >/dev/null 2>&1; }; then
    rm -f "$data/roundcube.db"
    runuser -u webmail -- "php$WEBAPP_PHP" "$dir/bin/initdb.sh" --dir "$dir/SQL" >>"$PHPANEL_LOG_FILE" 2>&1 || true
    if runuser -u webmail -- sqlite3 "$data/roundcube.db" "$q" >/dev/null 2>&1; then ok "Roundcube database initialised"
    else warn "Roundcube: database initialisation failed (see $PHPANEL_LOG_FILE)"; fi
  fi
}

install_snappymail() {
  local tag ver dir=/opt/phpanel/webmail/snappymail
  tag=$(latest_github_tag the-djmaze/snappymail) || { error "could not determine the SnappyMail version"; return 0; }
  ver=${tag#v}
  if [[ -f $dir/.phpanel-version && $(cat "$dir/.phpanel-version") == "$ver" ]]; then ok "SnappyMail $ver already installed"; else
    fetch_archive "https://github.com/the-djmaze/snappymail/releases/download/$tag/snappymail-$ver.zip" "$dir" \
      || { error "downloading SnappyMail $ver failed"; return 0; }
    echo "$ver" >"$dir/.phpanel-version"
    ok "SnappyMail $ver installed"
  fi
  # data outside the application directory
  install -d -o webmail -g webmail -m 750 /opt/phpanel/webmail/data/snappymail
  write_file "$dir/include.php" 640 <<'CONF'
<?php
define('APP_DATA_FOLDER_PATH', '/opt/phpanel/webmail/data/snappymail/');
CONF
  chown -R root:webmail "$dir"; chmod -R g+rX,o-rwx "$dir"
}

install_phpmyadmin() {
  local ver dir=/opt/phpanel/dbadmin/phpmyadmin base=https://files.phpmyadmin.net/phpMyAdmin sum
  ver=$(curl -fsSL --max-time 20 https://www.phpmyadmin.net/home_page/version.json 2>/dev/null | jq -r '.version' 2>/dev/null) || ver=
  [[ $ver =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || { error "could not determine the phpMyAdmin version"; return 0; }
  if [[ -f $dir/.phpanel-version && $(cat "$dir/.phpanel-version") == "$ver" ]]; then ok "phpMyAdmin $ver already installed"; else
    sum=$(curl -fsSL --max-time 20 "$base/$ver/phpMyAdmin-$ver-all-languages.tar.gz.sha256" 2>/dev/null | awk '{print $1}') || sum=
    [[ -n $sum ]] || { error "the official phpMyAdmin $ver checksum is missing"; return 0; }
    fetch_archive "$base/$ver/phpMyAdmin-$ver-all-languages.tar.gz" "$dir" "$sum" \
      || { error "downloading phpMyAdmin $ver failed"; return 0; }
    echo "$ver" >"$dir/.phpanel-version"
    ok "phpMyAdmin $ver installed (official checksum verified)"
  fi
  local bf; bf=$(grep -oP "blowfish_secret'\] = '\K[^']+" "$dir/config.inc.php" 2>/dev/null || true)
  [[ -n $bf ]] || bf=$(openssl rand -hex 16)
  install -d -o dbadmin -g dbadmin -m 750 /opt/phpanel/dbadmin/tmp
  write_file "$dir/config.inc.php" 640 <<CONF
<?php
// Generated by PH-PANEL [37]; autologin (signon) comes with the daemon
\$cfg['blowfish_secret'] = '$bf';
\$cfg['Servers'][1]['auth_type'] = 'cookie';
\$cfg['Servers'][1]['host'] = '127.0.0.1';
\$cfg['Servers'][1]['AllowNoPassword'] = false;
\$cfg['Servers'][1]['AllowRoot'] = false;
\$cfg['TempDir'] = '/opt/phpanel/dbadmin/tmp';
\$cfg['VersionCheck'] = false;
CONF
  chown -R root:dbadmin "$dir"; chmod -R g+rX,o-rwx "$dir"
}

setup_webapps_caddy() {
  # local diagnostic site, loopback only; the public addresses (mail.<domain>/webmail, HOSTNAME/phpmyadmin)
  # are generated from the panel DB [25][37]
  write_file /opt/phpanel/caddy/20-webapps-local.caddy <<CONF
http://127.0.0.1:8091 {
	bind 127.0.0.1
	handle_path /roundcube/* {
		root * /opt/phpanel/webmail/roundcube
		php_fastcgi unix//run/php/phpanel-webmail.sock
		file_server
	}
	handle_path /snappymail/* {
		root * /opt/phpanel/webmail/snappymail
		php_fastcgi unix//run/php/phpanel-webmail.sock
		file_server
	}
	handle_path /phpmyadmin/* {
		root * /opt/phpanel/dbadmin/phpmyadmin
		php_fastcgi unix//run/php/phpanel-dbadmin.sock
		file_server
	}
}
CONF
  if [[ $DRY_RUN != 1 ]]; then
    runuser -u caddy -- caddy validate --config /etc/caddy/Caddyfile --adapter caddyfile >>"$PHPANEL_LOG_FILE" 2>&1 \
      && ok "Caddyfile valid (with the web apps)" || error "caddy validate failed after adding the web apps"
  fi
}

step_09_webapps() {
  [[ $DRY_RUN == 1 ]] && { info "[dry-run] installing Roundcube, SnappyMail, phpMyAdmin"; return 0; }
  webapp_php_version || { error "no PHP version installed; skipping the web apps"; return 0; }
  info "php-fpm pools on PHP $WEBAPP_PHP"
  install -d -m 755 /opt/phpanel /opt/phpanel/webmail /opt/phpanel/dbadmin
  webapp_pool webmail webmail
  webapp_pool dbadmin dbadmin
  install_roundcube
  install_snappymail
  install_phpmyadmin
  run systemctl reload "php${WEBAPP_PHP}-fpm" || run systemctl restart "php${WEBAPP_PHP}-fpm" || true
  setup_webapps_caddy
}
