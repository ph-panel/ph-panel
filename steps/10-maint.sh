#!/usr/bin/env bash
# Step 10 – maintenance: daily DB dump for recovery [06], health check [12], cron jobs [43].

step_10_maint() {
  [[ $DRY_RUN == 1 ]] && { info "[dry-run] maintenance scripts and cron"; return 0; }
  install -d -m 755 /opt/phpanel/bin
  install -d -m 750 -o phpanel -g phpanel /opt/phpanel/logs 2>/dev/null || install -d -m 750 /opt/phpanel/logs
  install -d -m 700 /var/backups/phpanel/mysql

  write_file /opt/phpanel/bin/db-dump.sh 755 <<'SH'
#!/usr/bin/env bash
# Daily dump for disaster recovery [06]. Always keeps the last good copy.
set -uo pipefail
out=/var/backups/phpanel/mysql; log=/opt/phpanel/logs/db-dump.log; rc=0
install -d -m 700 "$out"
for db in $(mariadb -N -e 'show databases' | grep -Ev '^(information_schema|performance_schema|mysql|sys)$'); do
  if mariadb-dump --single-transaction "$db" | gzip >"$out/$db.sql.gz.tmp" && [[ -s $out/$db.sql.gz.tmp ]]; then
    mv "$out/$db.sql.gz.tmp" "$out/$db.sql.gz"
  else
    rm -f "$out/$db.sql.gz.tmp"; echo "$(date -Is) dump failed: $db" >>"$log"; rc=1
  fi
done
if [[ -f /opt/phpanel/data/panel.db ]]; then
  sqlite3 /opt/phpanel/data/panel.db ".backup '$out/panel.db.tmp'" && mv "$out/panel.db.tmp" "$out/panel.db" \
    || { echo "$(date -Is) panel.db backup failed" >>"$log"; rc=1; }
fi
exit $rc
SH

  write_file /opt/phpanel/bin/health-check.sh 755 <<'SH'
#!/usr/bin/env bash
# Daily health check [12]: services, disk, RAM, load, DB dump result. Log: /opt/phpanel/logs/health.log
set -uo pipefail
log=/opt/phpanel/logs/health.log; bad=0
say() { echo "$(date -Is) $*" >>"$log"; }
for s in caddy apache2 mariadb redis-server knot postfix dovecot rspamd unbound pure-ftpd fail2ban phpanel-web; do
  systemctl list-unit-files "$s.service" --no-legend | grep -q . || continue
  systemctl is-active --quiet "$s" || { say "SERVICE DOWN: $s"; systemctl restart "$s" 2>/dev/null; bad=1; }
done
d=$(df --output=pcent / | tail -1 | tr -dc 0-9); (( d > 85 )) && { say "DISK ${d}%"; bad=1; }
m=$(free | awk '/Mem/ {printf "%d", ($3/$2)*100}'); (( m > 90 )) && { say "RAM ${m}%"; bad=1; }
l=$(awk '{print $1}' /proc/loadavg); c=$(nproc)
awk -v l="$l" -v c="$c" 'BEGIN{exit !(l > c*0.8)}' && { say "LOAD $l (vCPU $c)"; bad=1; }
[[ -f /opt/phpanel/logs/db-dump.log && -n $(find /opt/phpanel/logs/db-dump.log -mtime -1 -size +0) ]] && { say "DB dump failed recently"; bad=1; }
(( bad )) || say "ok"
exit $bad
SH

  write_file /etc/cron.d/phpanel 644 <<'CRON'
# Generated by PH-PANEL – staggered schedule [43]
SHELL=/bin/bash
0 2 * * * root flock -n /run/phpanel-dbdump.lock nice -n 19 ionice -c3 /opt/phpanel/bin/db-dump.sh
0 6 * * * root flock -n /run/phpanel-health.lock nice -n 19 /opt/phpanel/bin/health-check.sh
CRON
  # logrotate for the panel logs [42]
  write_file /etc/logrotate.d/phpanel <<'CONF'
/opt/phpanel/logs/*.log {
    weekly
    rotate 4
    compress
    missingok
    notifempty
    copytruncate
    maxsize 100M
}
CONF
  ok "DB dump 02:00, health check 06:00, logrotate"
}
