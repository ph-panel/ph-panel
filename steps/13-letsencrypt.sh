#!/usr/bin/env bash
# Step 13 - Let's Encrypt certificate for the panel hostname [21]. lego uses the webroot that Caddy serves on :80,
# so Caddy never has to stop. On failure the self-signed certificate stays in place and the daily renew job retries.

LE_WEBROOT=/var/lib/phpanel/acme
LE_PATH=/var/lib/phpanel/lego

install_le_scripts() {
  install -d -m 755 /opt/phpanel/bin "$LE_WEBROOT" "$LE_PATH"
  write_file /opt/phpanel/bin/le-client.sh 755 <<'SH'
#!/usr/bin/env bash
# le-client.sh HOSTNAME EMAIL - obtain (or renew) the certificate for the panel hostname and install it.
# PHPANEL_LE_STAGING=1 uses the Let's Encrypt staging CA (for tests).
set -uo pipefail
host=${1:?hostname}; email=${2:?email}
webroot=/var/lib/phpanel/acme; path=/var/lib/phpanel/lego; log=/opt/phpanel/logs/le.log
server=()
if [[ ${PHPANEL_LE_STAGING:-0} == 1 ]]; then
  server=(--server https://acme-staging-v02.api.letsencrypt.org/directory)
  path=/var/lib/phpanel/lego-staging   # separate data: a staging certificate must never block the real one
fi
say() { echo "$(date -Is) $*" >>"$log"; }

# lego v5: "run" obtains a certificate, or renews it when fewer than --renew-days remain
if ! out=$(lego run --accept-tos --email "$email" --domains "$host" --path "$path" "${server[@]}" \
      --http --http.webroot "$webroot" --renew-days 30 2>&1); then
  say "lego failed for $host: $(tail -3 <<<"$out" | tr '\n' ' ')"
  exit 1
fi
action=(run)
crt=$path/certificates/$host.crt; key=$path/certificates/$host.key
[[ -s $crt && -s $key ]] || { say "lego reported success but $crt is missing"; exit 1; }
# a renew that found nothing to do leaves the files unchanged; installing them again is harmless
for dir in /opt/phpanel/ssl/panel /opt/phpanel/ssl/server /opt/phpanel/caddy/tls; do
  install -d -m 755 "$dir"
  install -m 644 "$crt" "$dir/fullchain.pem"
  case $dir in
    */panel) if id phpanel >/dev/null 2>&1; then install -m 640 -o root -g phpanel "$key" "$dir/privkey.pem"; else install -m 600 "$key" "$dir/privkey.pem"; fi ;;
    */caddy/tls) if getent group caddy >/dev/null; then install -m 640 -o root -g caddy "$key" "$dir/privkey.pem"; else install -m 600 "$key" "$dir/privkey.pem"; fi ;;
    *) install -m 600 "$key" "$dir/privkey.pem" ;;
  esac
done

# Caddy site for the panel hostname: HTTPS on 443 sends visitors to the panel on 8443; HTTP redirects to HTTPS.
# Written only now, because it references the certificate files above.
frag=/opt/phpanel/caddy/10-hostname.caddy
if [[ ! -f $frag ]] && command -v caddy >/dev/null; then
  install -d -m 755 /opt/phpanel/caddy
  cat >"$frag" <<CONF
# Generated by PH-PANEL: panel hostname
http://$host {
	handle /.well-known/acme-challenge/* {
		root * $webroot
		file_server
	}
	handle {
		redir https://$host{uri} permanent
	}
}
$host {
	tls /opt/phpanel/caddy/tls/fullchain.pem /opt/phpanel/caddy/tls/privkey.pem
	redir https://$host:8443{uri} temporary
}
CONF
  if ! cv=$(runuser -u caddy -- caddy validate --config /etc/caddy/Caddyfile --adapter caddyfile 2>&1); then
    rm -f "$frag"; say "Caddy rejected the hostname site, removed it: $(tail -2 <<<"$cv" | tr '\n' ' ')"
  fi
fi
for svc in postfix dovecot pure-ftpd caddy; do systemctl reload "$svc" 2>/dev/null || systemctl restart "$svc" 2>/dev/null || true; done
say "certificate for $host installed (${action[0]})"
exit 0
SH
  write_file /opt/phpanel/bin/le-renew.sh 755 <<'SH'
#!/usr/bin/env bash
# le-renew.sh - daily job: renew when fewer than 30 days remain; retry the first issuance if it never succeeded.
set -uo pipefail
. /var/lib/phpanel/facts.env 2>/dev/null || true
host=${PANEL_HOSTNAME:-}; [[ -n $host ]] || exit 0
email=${LE_EMAIL:-admin@$host}
crt=/var/lib/phpanel/lego/certificates/$host.crt
if [[ -s $crt ]]; then
  openssl x509 -checkend $((30*86400)) -noout -in "$crt" >/dev/null 2>&1 && exit 0
else
  ip=$(dig +short +time=3 +tries=1 A "$host" @127.0.0.1 | grep -E '^[0-9.]+$' | head -1)   # public DNS via Unbound, not /etc/hosts
  [[ -n $ip && $ip == "${IP_PUBLIC:-x}" ]] || exit 0   # DNS does not point here yet
fi
exec /opt/phpanel/bin/le-client.sh "$host" "$email"
SH
}

step_13_letsencrypt() {
  fact_set LE_STATUS skipped
  if [[ -z ${PANEL_HOSTNAME:-} ]]; then info "no --hostname: keeping the self-signed certificate"; return 0; fi
  [[ $DRY_RUN == 1 ]] && { info "[dry-run] request a Let's Encrypt certificate for $PANEL_HOSTNAME"; return 0; }
  have lego || { error "lego is not installed; cannot request a certificate"; fact_set LE_STATUS failed; return 0; }
  install_le_scripts
  install -d -m 750 -o phpanel -g phpanel /opt/phpanel/logs 2>/dev/null || install -d -m 750 /opt/phpanel/logs

  local ip email=${OPT_ADMIN_EMAIL:-}
  [[ -n $email && $email != *.local ]] || email=admin@$PANEL_HOSTNAME
  fact_set LE_EMAIL "$email"
  ip=$(dig +short +time=3 +tries=1 A "$PANEL_HOSTNAME" @127.0.0.1 | grep -E '^[0-9.]+$' | head -1) || true   # public DNS via Unbound, not /etc/hosts
  if [[ -z $ip || $ip != "${IP_PUBLIC:-x}" ]]; then
    warn "$PANEL_HOSTNAME resolves to '${ip:-nothing}', not to ${IP_PUBLIC:-the public IP}: certificate not requested; the daily job retries once DNS is right"
    fact_set LE_STATUS pending
  elif /opt/phpanel/bin/le-client.sh "$PANEL_HOSTNAME" "$email"; then
    local issuer; issuer=$(echo | openssl s_client -connect 127.0.0.1:8443 -servername "$PANEL_HOSTNAME" 2>/dev/null | openssl x509 -noout -issuer 2>/dev/null)
    ok "Let's Encrypt certificate installed for $PANEL_HOSTNAME (${issuer:-panel not reloaded yet})"
    fact_set LE_STATUS issued
  else
    warn "Let's Encrypt request failed (see /opt/phpanel/logs/le.log); keeping the self-signed certificate, the daily job retries"
    fact_set LE_STATUS failed
  fi
  write_file /etc/cron.d/phpanel-renew 644 <<'CRON'
# Generated by PH-PANEL: certificate renewal at 02:30 [43]
30 2 * * * root flock -n /run/phpanel-le.lock nice -n 19 /opt/phpanel/bin/le-renew.sh
CRON
}
